public class Professor {

    private int id;
    private String nome;
    private String cpf;
    private String telefone;
    private String especialidade;

    public Professor(int id,
                     String nome,
                     String cpf,
                     String telefone,
                     String especialidade){

        this.id=id;
        this.nome=nome;
        this.cpf=cpf;
        this.telefone=telefone;
        this.especialidade=especialidade;

    }

}